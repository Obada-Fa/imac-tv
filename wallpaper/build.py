#!/usr/bin/env python3
"""Build the Retro Circuit wallpaper into wallpaper/dist/.

The TV app's own tracing (tvapp/widgets/contours.py) and palette code run here, once, so the
wallpaper page never reads pixels: browsers taint file:// images, and tracing in JS would be slow.
Paths are traced on the WHOLE image (normalised 0..1); the page applies its own cover crop.

    python3 wallpaper/build.py [EXTRA_IMAGE_DIR ...]

Output: dist/retro-circuit/ (Lively, Wallpaper Engine and the Linux host all load it) and
dist/retro-circuit.zip (drag into Lively, or import the folder in Wallpaper Engine).
"""
import json
import os
import shutil
import sys
import zipfile

import gi
gi.require_version("GdkPixbuf", "2.0")
from gi.repository import GdkPixbuf  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
TVAPP = os.path.join(HERE, "..", "tvapp")
sys.path.insert(0, TVAPP)
from widgets import contours, shapes  # noqa: E402

SRC = os.path.join(HERE, "src")
RETRO = os.path.join(TVAPP, "assets", "retro")
DIST = os.path.join(HERE, "dist")
OUT = os.path.join(DIST, "retro-circuit")
EXTS = (".jpg", ".jpeg", ".png", ".webp")


def rgb_rows(pb, w):
    h = max(16, round(w * pb.get_height() / pb.get_width()))
    sm = pb.scale_simple(w, h, GdkPixbuf.InterpType.BILINEAR)
    data, stride, ch = sm.get_pixels(), sm.get_rowstride(), sm.get_n_channels()
    return [[tuple(data[y * stride + x * ch:y * stride + x * ch + 3]) for x in range(w)] for y in range(h)]


def palette(rows):
    """shapes.palette_from_bgrx wants cairo BGRX bytes: repack the small RGB copy."""
    h, w = len(rows), len(rows[0])
    data = bytes(b for row in rows for r, g, b_ in row for b in (b_, g, r, 0))
    return [[round(c, 3) for c in rgb] for rgb in shapes.palette_from_bgrx(data, w, h, w * 4)]


def analyse(path):
    pb = GdkPixbuf.Pixbuf.new_from_file(path)
    rows = rgb_rows(pb, contours.TRACE_WIDTH)
    paths = contours.valid_paths(contours.trace(rows))
    return {"w": pb.get_width(), "h": pb.get_height(), "palette": palette(rows),
            "paths": [[[round(x, 4), round(y, 4)] for x, y in p] for p in paths]}


def main(extra):
    if os.path.isdir(OUT):
        shutil.rmtree(OUT)
    shutil.copytree(SRC, OUT)
    os.makedirs(os.path.join(OUT, "images"))
    credits = {}
    try:
        with open(os.path.join(RETRO, "credits.json")) as f:
            credits = json.load(f)
    except (OSError, ValueError):
        pass
    images = []
    for folder in [RETRO] + list(extra):
        for name in sorted(os.listdir(folder)):
            if not name.lower().endswith(EXTS):
                continue
            src = os.path.join(folder, name)
            print("tracing", name, "...", flush=True)
            info = analyse(src)
            if not info["paths"]:
                print("  no usable contours: skipped")
                continue
            shutil.copy2(src, os.path.join(OUT, "images", name))
            info["file"] = "images/" + name
            images.append(info)
            print("  %d paths" % len(info["paths"]))
    if not images:
        raise SystemExit("no image had usable contours")
    with open(os.path.join(OUT, "data.js"), "w") as f:
        f.write("// generated by wallpaper/build.py\nwindow.WALLPAPER_DATA = ")
        json.dump({"images": images}, f, separators=(",", ":"))
        f.write(";\n")
    first = GdkPixbuf.Pixbuf.new_from_file(os.path.join(OUT, images[0]["file"]))
    first.scale_simple(400, round(400 * first.get_height() / first.get_width()),
                       GdkPixbuf.InterpType.BILINEAR).savev(os.path.join(OUT, "preview.jpg"), "jpeg", ["quality"], ["85"])
    if credits:
        with open(os.path.join(OUT, "images", "CREDITS.txt"), "w") as f:
            for name, c in sorted(credits.items()):
                f.write("%s: %s (%s)\n" % (name, c.get("name", ""), c.get("credit", "")))
    zpath = os.path.join(DIST, "retro-circuit.zip")
    with zipfile.ZipFile(zpath, "w", zipfile.ZIP_DEFLATED) as z:
        for root, _dirs, files in os.walk(OUT):
            for name in files:
                full = os.path.join(root, name)
                z.write(full, os.path.relpath(full, OUT))
    print("built %s (%d images) and %s" % (OUT, len(images), zpath))


if __name__ == "__main__":
    main(sys.argv[1:])
