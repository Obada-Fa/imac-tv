#!/usr/bin/env python3
"""
iMac 27" Audio Equalizer Manager (PulseAudio LADSPA mbeq_1197)
Controls custom acoustic DSP calibration for the iMac built-in speakers.
"""

import sys
import os
import subprocess
import json
from pathlib import Path

PLUGIN_PATH = str(Path.home() / ".ladspa/mbeq_1197.so")
HARDWARE_SINK = "alsa_output.pci-0000_00_1b.0.analog-stereo"
CONFIG_FILE = Path.home() / ".config/pulse/default.pa"
STATE_FILE = Path.home() / ".config/pulse/imac_eq_state.json"

BANDS = [
    ("50Hz", "50Hz gain (low shelving)"),
    ("100Hz", "100Hz gain"),
    ("156Hz", "156Hz gain"),
    ("220Hz", "220Hz gain"),
    ("311Hz", "311Hz gain"),
    ("440Hz", "440Hz gain"),
    ("622Hz", "622Hz gain"),
    ("880Hz", "880Hz gain"),
    ("1250Hz", "1.25kHz gain"),
    ("1750Hz", "1.75kHz gain"),
    ("2500Hz", "2.5kHz gain"),
    ("3500Hz", "3.5kHz gain"),
    ("5000Hz", "5kHz gain"),
    ("10000Hz", "10kHz gain"),
    ("20000Hz", "20kHz gain"),
]

PRESETS = {
    "music": {
        "name": "Music (Balanced High-Fidelity)",
        "desc": "Rich bass punch, acoustic warmth, cleared boxy mids, sparkling air.",
        "gains": [-3.0, 3.5, 3.0, 0.5, -2.5, -2.0, 0.0, 1.0, 2.0, 2.5, 3.0, 2.5, 3.0, 4.0, 0.0]
    },
    "bass": {
        "name": "Bass Boost (Warm & Punchy)",
        "desc": "Emphasized kick drum and bassline warmth for electronic, hip-hop, and rock.",
        "gains": [-1.0, 5.5, 4.5, 1.5, -2.0, -1.5, 0.0, 0.5, 1.5, 2.0, 2.5, 2.0, 2.5, 3.5, 0.0]
    },
    "vocal": {
        "name": "Vocal / TV & Movies (Dialogue Clarity)",
        "desc": "Boosted dialogue frequencies (1kHz-4kHz) with cut sub-rumble for TV & podcast clarity.",
        "gains": [-5.0, 1.0, 0.5, -1.0, -3.0, -2.5, 0.5, 2.0, 3.5, 4.0, 4.5, 3.5, 3.0, 3.0, -1.0]
    },
    "flat": {
        "name": "Flat (Unprocessed / Neutral)",
        "desc": "Bypasses acoustic compensation; flat 0dB response across all bands.",
        "gains": [0.0] * 15
    }
}

def run_cmd(args):
    res = subprocess.run(args, capture_output=True, text=True)
    return res.returncode, res.stdout.strip(), res.stderr.strip()

def get_current_eq_modules():
    code, out, _ = run_cmd(["pactl", "list", "modules", "short"])
    mods = []
    if code == 0:
        for line in out.splitlines():
            parts = line.split("\t")
            if len(parts) >= 3 and parts[1] == "module-ladspa-sink" and "imac_eq" in parts[2]:
                mods.append((parts[0], parts[2]))
    return mods

def get_sink_inputs():
    code, out, _ = run_cmd(["pactl", "list", "sink-inputs", "short"])
    inputs = []
    if code == 0 and out:
        for line in out.splitlines():
            parts = line.split("\t")
            if parts:
                inputs.append(parts[0])
    return inputs

def get_default_sink():
    code, out, _ = run_cmd(["pactl", "info"])
    if code == 0:
        for line in out.splitlines():
            if line.startswith("Default Sink:"):
                return line.split(":", 1)[1].strip()
    return ""

def update_default_pa(gains):
    ctrl_str = ",".join(f"{g:.1f}" for g in gains)
    content = f"""### Generated by imac-eq
.include /etc/pulse/default.pa

### Load Steve Harris Multiband EQ (mbeq_1197) calibrated for iMac 27-inch internal speakers
.nofail
load-module module-ladspa-sink sink_name=imac_eq sink_master={HARDWARE_SINK} plugin={PLUGIN_PATH} label=mbeq control={ctrl_str}
set-default-sink imac_eq
.fail
"""
    CONFIG_FILE.parent.mkdir(parents=True, exist_ok=True)
    CONFIG_FILE.write_text(content)

def save_state(preset_name, gains):
    STATE_FILE.parent.mkdir(parents=True, exist_ok=True)
    STATE_FILE.write_text(json.dumps({"preset": preset_name, "gains": gains}, indent=2))

def load_state():
    if STATE_FILE.exists():
        try:
            return json.loads(STATE_FILE.read_text())
        except Exception:
            pass
    return {"preset": "music", "gains": PRESETS["music"]["gains"]}

def apply_eq(gains, preset_name="custom"):
    ctrl_str = ",".join(f"{g:.1f}" for g in gains)
    existing_mods = get_current_eq_modules()
    
    # Load new sink with temporary or target name
    temp_sink = "imac_eq_new" if existing_mods else "imac_eq"
    code, out, err = run_cmd([
        "pactl", "load-module", "module-ladspa-sink",
        f"sink_name={temp_sink}",
        f"sink_master={HARDWARE_SINK}",
        f"plugin={PLUGIN_PATH}",
        "label=mbeq",
        f"control={ctrl_str}"
    ])
    if code != 0:
        print(f"Error loading equalizer module: {err}", file=sys.stderr)
        return False
    
    new_mod_id = out.strip()
    
    # Move active sink inputs to the new sink seamlessly
    for inp in get_sink_inputs():
        run_cmd(["pactl", "move-sink-input", inp, temp_sink])
    
    # Set default sink
    run_cmd(["pactl", "set-default-sink", temp_sink])
    
    # If we had existing modules, unload them and switch name back to imac_eq if needed
    for mod_id, _ in existing_mods:
        run_cmd(["pactl", "unload-module", mod_id])
        
    if temp_sink == "imac_eq_new":
        code2, out2, _ = run_cmd([
            "pactl", "load-module", "module-ladspa-sink",
            "sink_name=imac_eq",
            f"sink_master={HARDWARE_SINK}",
            f"plugin={PLUGIN_PATH}",
            "label=mbeq",
            f"control={ctrl_str}"
        ])
        if code2 == 0:
            for inp in get_sink_inputs():
                run_cmd(["pactl", "move-sink-input", inp, "imac_eq"])
            run_cmd(["pactl", "set-default-sink", "imac_eq"])
            run_cmd(["pactl", "unload-module", new_mod_id])

    update_default_pa(gains)
    save_state(preset_name, gains)
    print(f"Applied preset '{preset_name}' successfully.")
    return True

def cmd_status():
    state = load_state()
    def_sink = get_default_sink()
    mods = get_current_eq_modules()
    print("=== iMac 27\" Audio Equalizer Status ===")
    print(f"Default Sink:   {def_sink}")
    print(f"EQ Active:      {'YES (' + str(len(mods)) + ' active sink)' if mods else 'NO'}")
    print(f"Current Preset: {state.get('preset', 'custom')}")
    print("\n--- Equalizer Frequency Bands ---")
    gains = state.get("gains", PRESETS["music"]["gains"])
    for i, (freq, desc) in enumerate(BANDS):
        gain = gains[i] if i < len(gains) else 0.0
        bar_len = int(abs(gain) * 2)
        if gain > 0:
            bar = "+" + "#" * bar_len
        elif gain < 0:
            bar = "-" + "-" * bar_len
        else:
            bar = "0"
        print(f"  {freq:>7}: {gain:>+5.1f} dB  {bar:<16} ({desc})")

def cmd_presets():
    print("Available Presets:")
    for k, v in PRESETS.items():
        print(f"  {k:<8} : {v['name']}")
        print(f"             {v['desc']}")

def main():
    if len(sys.argv) < 2:
        cmd_status()
        print("\nUsage:")
        print("  imac-eq status               Show current EQ status and frequency curves")
        print("  imac-eq presets              List available acoustic presets")
        print("  imac-eq apply <preset>       Apply preset (music, bass, vocal, flat)")
        print("  imac-eq set <band> <gain>    Adjust gain for band (e.g. imac-eq set 100Hz +4.0)")
        return

    cmd = sys.argv[1].lower()
    if cmd == "status":
        cmd_status()
    elif cmd == "presets":
        cmd_presets()
    elif cmd in ("apply", "load"):
        if len(sys.argv) < 3:
            print("Specify preset name: music, bass, vocal, flat")
            sys.exit(1)
        target = sys.argv[2].lower()
        if target in PRESETS:
            apply_eq(PRESETS[target]["gains"], target)
        else:
            print(f"Unknown preset '{target}'. Options: {', '.join(PRESETS.keys())}")
            sys.exit(1)
    elif cmd == "set":
        if len(sys.argv) < 4:
            print("Usage: imac-eq set <band> <gain_dB> (e.g. imac-eq set 100Hz 4.0)")
            sys.exit(1)
        band_arg = sys.argv[2].lower().replace(" ", "")
        try:
            gain_val = float(sys.argv[3])
        except ValueError:
            print("Gain must be a number in dB")
            sys.exit(1)
        
        idx = -1
        for i, (f, _) in enumerate(BANDS):
            if f.lower() == band_arg or f.lower().replace("hz", "") == band_arg:
                idx = i
                break
        if idx == -1:
            print(f"Band '{band_arg}' not found. Available bands: {', '.join(f for f, _ in BANDS)}")
            sys.exit(1)
            
        state = load_state()
        gains = list(state.get("gains", PRESETS["music"]["gains"]))
        gains[idx] = max(-70.0, min(30.0, gain_val))
        apply_eq(gains, "custom")
    else:
        print(f"Unknown command: {cmd}")
        sys.exit(1)

if __name__ == "__main__":
    main()
